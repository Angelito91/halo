//! Tabla única de casos de paridad.
//!
//! Cada entrada es a la vez el caso del corpus y su registro de divergencia
//! esperada: el snippet, la divergencia (motivo + fase que la cierra) y las
//! features del catálogo que el caso ejercita. Así una divergencia no puede
//! existir sin un caso que la ejercite, y el snippet vive en un solo sitio.

use super::parity::{KnownDivergence, ParityCase, Phase};

/// Declara la divergencia esperada de un caso.
const fn diverges(id: &'static str, reason: &'static str, phase: Phase) -> Option<KnownDivergence> {
    Some(KnownDivergence { id, reason, phase })
}

